"""Generate shared explicit UI catalogs; never translate stored user content."""
import ast
import json
import re
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
rows = [line.split('\t') for line in (ROOT/'tools/ui-translations.tsv').read_text('utf-8').splitlines() if line]
assert all(len(row) == 4 for row in rows)
catalog = {row[0]: dict(zip(('en','ja','zh-TW'), row[1:])) for row in rows}
(ROOT/'assets/ui-locales.json').write_text(json.dumps(catalog, ensure_ascii=False, indent=2), encoding='utf-8')
(ROOT/'mobile/lib/ui_messages.dart').write_text('// Generated by tools/generate_ui_locales.py\nconst uiMessages = '+json.dumps(catalog, ensure_ascii=False, indent=2)+';\n', encoding='utf-8')

# Preserve const widget construction; only explicit UI literals become LocalText.
for path in (ROOT/'mobile/lib').glob('*.dart'):
    if path.name in ('i18n.dart','ui_messages.dart'): continue
    source=path.read_text('utf-8')
    updated=re.sub(r'(?<![\w.])Text\((\s*)(?=[\'\"])',r'LocalText(\1',source)
    # Common presentation helpers receive labels, never stored record fields.
    if path.name in ('profile_ui.dart','profile_pages.dart','home_screen.dart'):
        updated=re.sub(r'(?<![\w.])Text\((\s*)(title|subtitle|label|hint|kicker)(?=\s*[,\)])',r'LocalText(\1\2',updated)
    if path.name=='shell.dart': updated=re.sub(r'(?<![\w])Text\((\s*)labels\[i\]', r'LocalText(\1labels[i]', updated)
    if updated != source and "import 'i18n.dart';" not in updated: updated="import 'i18n.dart';\n"+updated
    if updated!=source:path.write_text(updated,encoding='utf-8')

# Desktop: wrap explicit UI literals only, keep data keys and storage values intact.
controls={'Text','TextButton','FilledButton','OutlinedButton','ElevatedButton','DropdownOption'}
helpers={'head','action','info_row'}
for path in ROOT.glob('*.py'):
    if path.name=='i18n.py':continue
    source=path.read_text('utf-8-sig')
    tree=ast.parse(source); edits={}
    lines=source.splitlines(keepends=True)
    starts=[0]
    for line in lines: starts.append(starts[-1]+len(line))
    def pos(line,col): return starts[line-1]+len(lines[line-1].encode('utf-8')[:col].decode('utf-8'))
    for node in ast.walk(tree):
        if not isinstance(node,ast.Call):continue
        name=node.func.attr if isinstance(node.func,ast.Attribute) else node.func.id if isinstance(node.func,ast.Name) else ''
        args=list(node.args[:1]) if name in controls else list(node.args) if name in helpers else []
        args += [k.value for k in node.keywords if k.arg in ('label','hint_text','tooltip','title','subtitle')]
        for arg in args:
            if isinstance(arg,ast.Constant) and isinstance(arg.value,str) and arg.value in catalog:
                a,b=pos(arg.lineno,arg.col_offset),pos(arg.end_lineno,arg.end_col_offset)
                edits[(a,b)]='tr('+source[a:b]+')'
    if not edits:continue
    for (a,b),value in sorted(edits.items(),reverse=True):source=source[:a]+value+source[b:]
    if 'from i18n import tr' not in source:
        tree=ast.parse(source)
        after=0
        for node in tree.body:
            if isinstance(node,ast.Expr) and isinstance(node.value,ast.Constant) and isinstance(node.value.value,str) or isinstance(node,ast.ImportFrom) and node.module=='__future__': after=node.end_lineno
            else:break
        parts=source.splitlines(keepends=True);parts.insert(after,'from i18n import tr\n');source=''.join(parts)
    path.write_text(source,encoding='utf-8')
print(f'Generated {len(catalog)} UI translations in 4 languages')
