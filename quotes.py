_current: dict = {"index": None}


def _read_last() -> int | None:
    try:
        with open(STATE_PATH, encoding="utf-8") as f:
            return json.load(f).get("quote_index")
    except (OSError, ValueError):
        return None


def _write_last(index: int) -> None:
    try:
        with open(STATE_PATH, "w", encoding="utf-8") as f:
            json.dump({"quote_index": index}, f, ensure_ascii=False)
    except OSError:
        pass


def _pick() -> int:
    """随机抽一条，尽量不与上次相同。"""
    last = _read_last()
    if len(QUOTES) < 2:
        return 0
    index = last
    while index == last:
        index = random.randrange(len(QUOTES))
    _write_last(index)
    return index


def current_quote() -> tuple[str, str]:
    """本次运行要显示的那句（进程内只抽一次）。"""
    if _current["index"] is None:
        _current["index"] = _pick()
    return QUOTES[_current["index"]]


def next_quote() -> tuple[str, str]:
    """手动换一句。"""
    _current["index"] = _pick()
    return QUOTES[_current["index"]]
